/// 全部数值阈值集中在此处，便于调整与测试。
library;

/// 高程中值滤波窗口（点数，必须为奇数）。见设计文档 8.1。
const int kElevationFilterWindow = 5;

/// 单次上升超过该值（米）才计入爬升。见设计文档 8.1。
const double kElevationGainThresholdM = 1.0;

/// 速度滑动平均窗口（点数，必须为奇数）。见设计文档 8.1。
///
/// 只用于**读数值**（最高速，见 `summary.dart`）：窗口越短越贴近瞬时峰值，
/// 代价是 GPS 毛刺会更明显地抬高读数。曲线绘制另用 [kSpeedCurveFilterWindow]，
/// 两个窗口不要混用。
const int kSpeedFilterWindow = 5;

/// 速度**曲线**的平滑窗口（点数，必须为奇数），只作用于画线。
///
/// 比 [kSpeedFilterWindow] 大得多，因为两者的目标不同：读数只要一个数，抹平
/// 毛刺就行；曲线要读的是趋势，残余噪声会直接变成看得见的锯齿。GPS 瞬时速度
/// 的噪声 σ≈0.26 m/s，5 点窗口后仍有 0.12 m/s，映射到 140px 高的图上就是两三
/// 个像素的细齿——真机上「有锯齿」看到的就是这个。窗口取 31（2 秒一个采样点
/// 时约 62 秒），噪声降到 0.05 m/s 以内；而真实的速度起伏是分钟级的，几乎不
/// 会被抹掉。
const int kSpeedCurveFilterWindow = 31;

/// 心率 / 踏频 / 功率曲线的平滑窗口（点数，必须为奇数）。
///
/// 这三项来自传感器逐点原始值，逐点抖动很大，直接连起来是一条毛刺线：真机上
/// 看着「不圆润」的其实是噪声，不是骑行节奏。窗口取 21：2 秒一个采样点时约
/// 42 秒，足以把逐点抖动摊平；而心率与踏频的真实变化本来就是分钟级的，不会
/// 跟着一起被抹平。
///
/// 平滑只作用于画线用的序列：页面上的平均 / 最高读数仍取原始值
/// （见 `summary.dart`），不会跟着变。
const int kSensorCurveFilterWindow = 21;

/// 静止判定速度阈值（m/s），等于 1 km/h。见设计文档 8.2。
const double kStationarySpeedMps = 1.0 / 3.6;

/// 轨迹点写入：与上一点的最小距离（米）。见设计文档 6.3 规则 1。
const double kMinWriteDistanceM = 5.0;

/// 轨迹点写入：距上次写入的最大时间间隔（毫秒）。见设计文档 6.3 规则 1。
const int kMaxWriteIntervalMs = 2000;

/// GPS 断点判定：相邻点时间间隔超过该值视为信号丢失。见设计文档 9.3。
const int kGpsGapMs = 10000;

// ---------------------------------------------------------------------------
// 实时轨迹缩略图（骑行界面指标条下方那张小地图，见设计文档 9.4）
//
// 与落盘那套（[kMinWriteDistanceM] / [kMaxWriteIntervalMs]）是两回事：落盘要
// 尽量忠实，缩略图只要形状。按落盘的密度喂给一张 120pt 高的图，一小时骑行有
// 三千多个点，全画上去看不出更多东西，只多烧 CPU。因此另有一套更稀的抽稀。
// ---------------------------------------------------------------------------

/// 实时轨迹相邻两点的最小距离（米）。见设计文档 9.4。
const double kLiveTrackMinDistanceM = 25.0;

/// 实时轨迹相邻两点的最大时间间隔（毫秒）。见设计文档 9.4。
const int kLiveTrackMaxIntervalMs = 15000;

/// 实时轨迹保留的最大点数。超出时折半压缩（见 `RecordingSession`）。
///
/// 取 400：360dp 宽、120dp 高的图上，400 个点在长距离骑行里也够铺出弯道的
/// 形状了，再多只是重复同一条线。
const int kLiveTrackMaxPoints = 400;

/// 传感器批量提交点数。见设计文档 6.3 规则 2。
const int kSensorBatchSize = 10;

/// 速度着色（m/s）与功率着色（W）的归一化上限。见设计文档 8.2。
const double kColorScaleMaxSpeedMps = 15.0;

/// 曲线平滑的切线除数。
///
/// 标准 Catmull-Rom 用 6（切线 = 前后点差 / 2，再取三分之一作为贝塞尔控制点）。
/// 抽稀到 240 个点铺在三百多像素宽里，每段只有一两个像素，标准张力画出来和
/// 折线几乎没区别——真机上看到的「不圆润」就是这个。放宽到 4 把切线拉长，
/// 拐角明显被抹圆；代价是控制点会略微越过极值，画笔按图表区域裁剪即可。
const double kCurveTensionDivisor = 4.0;

/// 曲线纵轴的顶部留白倍数。
///
/// 纵轴上限原来直接取最大值，曲线峰顶正好贴着图表上沿，再被 `clipRect` 裁一刀
/// 就成了「平顶」——看着像被切掉一块。抬高 6% 让峰顶落在框内。
const double kCurveTopHeadroom = 1.06;

/// 物理合理速度上限（m/s），约 108 km/h。
///
/// 这是补充阈值（设计文档 8.1 只列了爬升与最高速两个陷阱）：相邻两点的
/// 隐含速度超过该值时判定为 GPS 跳变，不计入距离、也不计入移动/静止时长。
const double kMaxPlausibleSpeedMps = 30.0;

/// 高程跳变检查：变化幅度小于该值（米）时不做合理性判断。
///
/// 取 10：静止时 GPS 高程漂移通常在几米内，不该被当成异常；而「首个定位点
/// 给出 0、次点才是真实海拔」这类问题通常差上百米。
const double kSuspectElevationJumpM = 10.0;

/// 高程跳变检查：允许的最大坡度（垂直变化 / 水平位移）。
///
/// 骑行不可能持续骑出 30% 以上的坡，取 0.5 留足余量，只拦「水平几乎没动
/// 却在垂直方向变了上百米」这类物理上不成立的点。
const double kMaxPlausibleGrade = 0.5;

// ---------------------------------------------------------------------------
// 估算功率（没接功率计时，由速度、坡度与体重推算，见 analysis/power.dart）
// ---------------------------------------------------------------------------

/// 重力加速度（m/s²）。
const double kGravity = 9.80665;

/// 滚动阻力系数。柏油路面公路胎约 0.004~0.006，取中间值。
const double kRollingResistance = 0.005;

/// 空气密度（kg/m³）。
const double kAirDensity = 1.225;

/// 迎风面积 × 风阻系数（m²）。休闲骑姿约 0.3~0.4。
const double kDragArea = 0.32;

/// 用户没设体重时，估算功率用的兜底体重（公斤）。
///
/// 设置页的默认体重（`data/settings_repository.dart` 里的 `kDefaultWeightKg`）
/// 取的就是这个值——同一个数字写两处迟早会分叉。
const double kDefaultRiderWeightKg = 70.0;

/// 拟合坡度用的时间窗口（毫秒）。
///
/// 高程在秒级尺度上的噪声有几米，而半分钟里真实的爬升可能只有一两米，窗口太短
/// 拟合出来的基本是噪声的形状。30 秒在 6 m/s 时约 180 米水平距离，足够把噪声
/// 摊平；代价是爬坡读数有半分钟滞后——本来就是估算，界面已写明。
const int kGradeWindowMs = 30000;

/// 拟合坡度所需的最小水平位移（米）。低于此值不做拟合，按平路处理。
const double kMinGradeRunM = 50.0;

/// 拟合坡度的绝对值上限（12%）。
const double kMaxGrade = 0.12;
